#!/usr/bin/env python3
"""Regenerate internal/agents/table_gen.go from vercel-labs/skills src/agents.ts.

Usage: scripts/gen_agents.py <path-to-vercel-labs-skills-checkout>
"""
import json
import re
import subprocess
import sys

ENV_BASES = {
    "home": ("", ""),
    "configHome": ("XDG_CONFIG_HOME", ".config"),
    "codexHome": ("CODEX_HOME", ".codex"),
    "claudeHome": ("CLAUDE_CONFIG_DIR", ".claude"),
    "vibeHome": ("VIBE_HOME", ".vibe"),
    "hermesHome": ("HERMES_HOME", ".hermes"),
    "autohandHome": ("AUTOHAND_HOME", ".autohand"),
    "grokHome": ("GROK_HOME", ".grok"),
    "sarvamHome": ("SARVAM_HOME", ".sarvam"),
}

# Agents whose detection lives in helper functions upstream.
MANUAL_DETECT = {
    "openclaw": [("", "", ".openclaw"), ("", "", ".clawdbot"), ("", "", ".moltbot")],
    "kimchi": [("", "", ".config/kimchi")],
    "minimax-code": [("", "", ".minimax"), "/Applications/MiniMax Code.app"],
    "posit-assistant": [("", "", ".posit/assistant"), ("", "", ".positai")],
    "zcode": [("", "", ".zcode"), "/Applications/ZCode.app"],
    "zed": [("XDG_CONFIG_HOME", ".config", "zed")],
}
MANUAL_DIR = {"openclaw": ("", "", ".openclaw/skills")}


def q(s):
    return json.dumps(s)


def loc(t):
    if isinstance(t, str):
        return "A(%s)" % q(t)
    return "P(%s, %s, %s)" % (q(t[0]), q(t[1]), q(t[2]))


def parse_path(expr):
    expr = expr.strip()
    m = re.fullmatch(r"(\w+)", expr)
    if m and m.group(1) in ENV_BASES:
        env, default = ENV_BASES[m.group(1)]
        return (env, default, "")
    m = re.fullmatch(r"join\((\w+),\s*(.+)\)", expr)
    if not m or m.group(1) not in ENV_BASES:
        return None
    env, default = ENV_BASES[m.group(1)]
    return (env, default, "/".join(re.findall(r"'([^']*)'", m.group(2))))


def main(src):
    text = open(src + "/src/agents.ts").read()
    body = text[text.index("export const agents"):]
    blocks = re.split(r"\n  (?='?[a-z0-9-]+'?: \{)", body)[1:]
    rows, skipped = [], []
    for b in blocks:
        key = re.match(r"'?([a-z0-9-]+)'?:", b).group(1)
        name = re.search(r"displayName: '([^']+)'", b).group(1)
        g = re.search(r"globalSkillsDir:\s*([^\n]+?),?\n", b).group(1).strip()
        if g == "undefined":
            skipped.append(key)
            continue
        d = MANUAL_DIR.get(key) or parse_path(g)
        det = re.search(r"detectInstalled: async \(\) => \{(.*?)\n    \}", b, re.S)
        body_ = det.group(1) if det else ""
        if key in MANUAL_DETECT:
            dets = MANUAL_DETECT[key]
        else:
            dets = []
            for e in re.findall(r"existsSync\(((?:join\([^()]*\))|(?:'[^']*')|\w+)\)", body_):
                if e.startswith("'"):
                    dets.append(e.strip("'"))
                else:
                    p = parse_path(e)
                    if p:
                        dets.append(p)
        if d is None or not dets:
            skipped.append(key)
            continue
        rows.append('\t{Key: %s, Name: %s, Dir: %s, Detect: []Loc{%s}},' % (
            q(key), q(name), loc(d), ", ".join(loc(x) for x in dets)))
    sha = subprocess.check_output(["git", "-C", src, "rev-parse", "--short", "HEAD"], text=True).strip()
    print("// Code generated by scripts/gen_agents.py from vercel-labs/skills src/agents.ts")
    print("// (MIT License, Copyright (c) 2026 Vercel, Inc.) at commit %s. DO NOT EDIT." % sha)
    print("// Project-only agents without a global skills folder are omitted: %s." % ", ".join(skipped))
    print()
    print("package agents")
    print()
    print("var table = []Agent{")
    print("\n".join(rows))
    print("}")


if __name__ == "__main__":
    main(sys.argv[1])
